#!/usr/bin/env python3
"""Regenerate checklist data from items*.md (run after editing checklists).

Writes:
- _data/checklist_schema.yml (Schema.org JSON-LD data for the site)
- skills/wordpress-security-checklist/references/checklist.md (AI skill reference)

Fails if the locales do not share the same item IDs in the same order, or if
the skill's references/checks.md does not have exactly one entry per item ID.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "_data" / "checklist_schema.yml"
SKILL_REFS = ROOT / "skills" / "wordpress-security-checklist" / "references"
SKILL_CHECKLIST = SKILL_REFS / "checklist.md"
SKILL_CHECKS = SKILL_REFS / "checks.md"

LOCALES = [
    ("en", "English", "items.md", "https://wpsecuritychecklist.org/items/"),
    ("br", "Português (BR)", "items.br.md", "https://wpsecuritychecklist.org/br/items/"),
    ("es", "Español", "items.es.md", "https://wpsecuritychecklist.org/es/items/"),
    ("ja", "日本語", "items.ja.md", "https://wpsecuritychecklist.org/ja/items/"),
]

SECTION_RE = re.compile(r"^##\s+(.+?)(?:<span[^>]*></span>)?\s*$", re.MULTILINE)
CHECK_ID_RE = re.compile(r"^###\s+(wsc-[a-z0-9-]+)\s*$", re.MULTILINE)

LABEL_RE = re.compile(
    r'<label><input type="checkbox" data-item-id="([^"]+)"\s*/>\s*(.+?)</label>',
    re.DOTALL,
)


def parse_items(path: Path) -> list[dict[str, str]]:
    raw = path.read_text(encoding="utf-8")
    if raw.startswith("---"):
        raw = raw.split("---", 2)[2]
    sections = [(m.start(), m.group(1).strip()) for m in SECTION_RE.finditer(raw)]
    items: list[dict[str, str]] = []
    for m in LABEL_RE.finditer(raw):
        iid, name = m.group(1), m.group(2)
        name = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", name)
        name = re.sub(r"\{:[^}]+\}", "", name)
        name = re.sub(r"\s+", " ", name).strip()
        section = ""
        for pos, title in sections:
            if pos < m.start():
                section = title
        items.append({"id": iid, "name": name, "section": section})
    return items


def check_locales(out: dict[str, list[dict[str, str]]]) -> list[str]:
    errors: list[str] = []
    en_ids = [row["id"] for row in out.get("en", [])]
    for lang, rows in out.items():
        ids = [row["id"] for row in rows]
        if ids != en_ids:
            missing = sorted(set(en_ids) - set(ids))
            extra = sorted(set(ids) - set(en_ids))
            detail = f"missing {missing}, extra {extra}" if missing or extra else "different order"
            errors.append(f"{lang}: item IDs differ from en ({detail})")
    return errors


def write_skill_checklist(out: dict[str, list[dict[str, str]]]) -> None:
    by_lang = {lang: {row["id"]: row for row in rows} for lang, rows in out.items()}
    lines = [
        "<!-- Generated by scripts/sync-checklist-schema.py from items*.md. Do not hand-edit. -->",
        "",
        "# WordPress Security Checklist items",
        "",
        "This is the canonical item list. Each item has a stable ID and its wording in every",
        "language the website supports. Checklist pages:",
        "",
    ]
    for lang, label, _, url in LOCALES:
        if lang in out:
            lines.append(f"- {label} (`{lang}`): {url}")
    lines.append("")
    section = None
    for row in out["en"]:
        if row["section"] != section:
            section = row["section"]
            lines += [f"## {section}", ""]
        lines.append(f"### {row['id']}")
        lines.append("")
        for lang, *_ in LOCALES:
            if lang in by_lang and row["id"] in by_lang[lang]:
                lines.append(f"- **{lang}:** {by_lang[lang][row['id']]['name']}")
        lines.append("")
    SKILL_CHECKLIST.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def check_skill_checks(out: dict[str, list[dict[str, str]]]) -> list[str]:
    if not SKILL_CHECKS.exists():
        return [f"{SKILL_CHECKS.relative_to(ROOT)} is missing"]
    found = CHECK_ID_RE.findall(SKILL_CHECKS.read_text(encoding="utf-8"))
    ids = [row["id"] for row in out["en"]]
    errors: list[str] = []
    dupes = sorted({i for i in found if found.count(i) > 1})
    missing = [i for i in ids if i not in found]
    extra = sorted(set(found) - set(ids))
    if dupes:
        errors.append(f"checks.md: duplicate entries {dupes}")
    if missing:
        errors.append(f"checks.md: no entry for {missing}")
    if extra:
        errors.append(f"checks.md: entries for unknown IDs {extra}")
    return errors


def main() -> None:
    out: dict[str, list[dict[str, str]]] = {}
    for lang, _, filename, _ in LOCALES:
        p = ROOT / filename
        if not p.exists():
            continue
        out[lang] = parse_items(p)

    lines = [
        "# Generated by scripts/sync-checklist-schema.py — do not hand-edit.",
        "",
    ]
    for lang, rows in out.items():
        lines.append(f"{lang}:")
        for row in rows:
            nid = row["id"].replace("\\", "\\\\").replace('"', '\\"')
            nname = row["name"].replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'  - id: "{nid}"')
            lines.append(f'    name: "{nname}"')
        lines.append("")

    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    for lang, rows in out.items():
        print(f"{lang}: {len(rows)} items")
    print(f"Wrote {OUT.relative_to(ROOT)}")

    write_skill_checklist(out)
    print(f"Wrote {SKILL_CHECKLIST.relative_to(ROOT)}")

    errors = check_locales(out) + check_skill_checks(out)
    for err in errors:
        print(f"ERROR: {err}", file=sys.stderr)
    if errors:
        sys.exit(1)


if __name__ == "__main__":
    main()
